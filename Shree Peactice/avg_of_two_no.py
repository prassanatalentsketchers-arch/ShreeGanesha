"""
WAP to input 2 floating point numbers & print their average.
"""

num1 = float(input("Enter the First Number : "))  # Floating Number 1
num2 = float(input("Enter the Second Number : "))  # Floating Number 2

avg = (num1 + num2) / 2  # It returns float values in all case because  / operator returns the float type value only

print("\nThe average is : ", avg)  # it prints the average value referred by avg variable
