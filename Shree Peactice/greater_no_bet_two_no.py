"""
WAP to input 2 int numbers, 'a' and 'b'.
Print True if 'a' is greater than or equal to 'b'. If not print False.
"""

a = int(input("Enter the First Number : "))  # This is first no
b = int(input("Enter the Second Number : "))  # This is second no

if a >= b:
    print(True)
else:
    print(False)

